import type { CardDef } from "../game/types";
const creature = (
  id: string,
  name: string,
  cost: number,
  attack: number,
  health: number,
  art: number,
  region: CardDef["region"] = "neutral",
  extra: Partial<CardDef> = {},
): CardDef => ({
  id,
  name,
  cost,
  attack,
  health,
  art,
  region,
  kind: "creature",
  rarity: cost >= 5 ? "Rara" : "Comum",
  text: "",
  ...extra,
});
